// A real Excel workbook (.xlsx) from rows of cells, with the few styles the team's reports use: a
// title row, light-blue headings, bold names, whole numbers and pesos with commas, percentages
// coloured by how far along they are, and a red bold Grand Total. Written with Node's own zip
// (deflate and CRC-32), no library.

import { crc32, deflateRawSync } from "node:zlib";

export type Cell = { v: string | number | null; s?: Style } | string | number | null;
export type Style = "title" | "head" | "name" | "int" | "money" | "pct" | "totalName" | "totalInt" | "totalMoney" | "totalPct" | "text" | "centavos";
export type Sheet = { name: string; rows: Cell[][]; widths?: number[]; merges?: string[] };

